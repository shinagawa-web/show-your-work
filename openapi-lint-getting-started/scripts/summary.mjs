import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const results = process.argv[2];
const read = (name) => readFileSync(join(results, name), 'utf8');
const lines = (name) => read(name).split('\n');
const json = (name) => JSON.parse(read(name));

const need = (value, what, name) => {
  if (value === undefined) throw new Error(`no ${what} in ${name}`);
  return value;
};
const exitCode = (name) => need(lines(name).find((l) => l.startsWith('exit code: ')), 'exit code line', name).slice('exit code: '.length);
const countLine = (name) => need(lines(name).find((l) => l.startsWith('❌ ') || l.startsWith('Woohoo! ')), 'count line', name);
const ignoredLine = (name) => need(lines(name).find((l) => / problems? (are|is) explicitly ignored\.$/.test(l)), 'ignored line', name);
const counts = (name) => {
  const text = read(name);
  const num = (re) => Number(text.match(re)?.[1] ?? 0);
  return {
    errors: num(/failed with (\d+) errors?/),
    warnings: num(/(?:and|You have) (\d+) warnings?/),
    ignored: num(/(\d+) problems? (?:are|is) explicitly ignored/),
  };
};
const problemRow = (p) => `| \`${p.ruleId}\` | ${p.severity} | \`${p.location[0].pointer}\` |`;
const fence = (lang, text) => ['```' + lang, text.trimEnd(), '```'];
const annotations = (name) => {
  const found = lines(name).filter((l) => l.startsWith('::'));
  if (found.length === 0) throw new Error(`no annotation lines in ${name}`);
  return found;
};

const out = ['# openapi-lint-getting-started', ''];

out.push('## Section 2: findings with no config', '');
out.push('Findings of `redocly lint openapi.yaml` with no config file, in the order they were reported.', '');
out.push('| rule | severity | JSON pointer |', '| --- | --- | --- |');
for (const p of json('section2-lint.json').problems) out.push(problemRow(p));
out.push('', ...fence('', [countLine('section2-lint.txt'), `exit code: ${exitCode('section2-lint.txt')}`].join('\n')), '');

out.push('## Section 3: a camelCase rule', '');
out.push('`redocly.yaml`:', '', ...fence('yaml', read('work/section3/redocly.yaml')), '');
out.push('The finding of the added rule when linting with this config.', '');
out.push('| rule | severity | JSON pointer |', '| --- | --- | --- |');
for (const p of json('section3-lint.json').problems.filter((p) => p.ruleId.startsWith('rule/'))) out.push(problemRow(p));
out.push('', 'With `extends`:', '');
out.push(...fence('', [countLine('section3-lint.txt'), `exit code: ${exitCode('section3-lint.txt')}`].join('\n')), '');
out.push('Without `extends` (only `rules`):', '');
out.push(...fence('', [countLine('section3-lint-without-extends.txt'), `exit code: ${exitCode('section3-lint-without-extends.txt')}`].join('\n')), '');

out.push('## Section 4: the ignore file', '');
out.push('`.redocly.lint-ignore.yaml` generated by `redocly lint --generate-ignore-file openapi.yaml` with the section 3 config:', '');
out.push(...fence('yaml', read('section4-lint-ignore.yaml')), '');
out.push('`redocly lint openapi.yaml` with the ignore file:', '');
out.push(...fence('', [countLine('section4-lint.txt'), ignoredLine('section4-lint.txt'), `exit code: ${exitCode('section4-lint.txt')}`].join('\n')), '');

out.push('## Section 5: one change on top of the ignore file', '');
out.push('`redocly lint openapi.yaml` after one change to the section 4 state (config and ignore file in place).', '');
const cases = [
  ['1', 'add `updated_at` to the ignored `Order` schema', 'section5-error-in-excluded-schema.txt'],
  ['2', 'add a string `quantity` example to `GET /orders/{id}/items/{itemId}`', 'section5-warn-only.txt'],
  ['3', 'case 1, then regenerate the ignore file', 'section5-regenerate.txt'],
];
out.push('| case | change | exit code | errors | warnings | ignored |', '| --- | --- | ---: | ---: | ---: | ---: |');
for (const [n, change, file] of cases) {
  const c = counts(file);
  out.push(`| ${n} | ${change} | ${exitCode(file)} | ${c.errors} | ${c.warnings} | ${c.ignored} |`);
}
out.push('', 'Annotation lines of `--format=github-actions` for case 1 and case 2:', '');
out.push(...fence('', [...annotations('section5-error-in-excluded-schema-github-actions.txt'), ...annotations('section5-warn-only-github-actions.txt')].join('\n')), '');
out.push('Ignore file before and after regenerating in case 3:', '');
out.push(...fence('diff', read('section5-regenerate-ignore.diff')), '');

out.push('## Section 6: lint passes, the implementation does not check access', '');
out.push(`\`GET /orders/{id}\` for the order created by user A, sent to the server while the section 4 lint ends with exit code ${exitCode('section4-lint.txt')}.`, '');
out.push('| order access check | caller | status |', '| --- | --- | ---: |');
const requests = [
  ['on', 'check-a'], ['on', 'check-b'], ['on', 'check-no-token'],
  ['removed', 'skip-a'], ['removed', 'skip-b'], ['removed', 'skip-c'], ['removed', 'skip-no-token'],
];
for (const [state, name] of requests) {
  const file = lines(`section6-${name}.txt`);
  const caller = file[0].replace(/^request: .* as /, '');
  const status = need(file.find((l) => l.startsWith('status: ')), 'status line', name).slice('status: '.length);
  out.push(`| ${state} | ${caller} | ${status} |`);
}
out.push('');

writeFileSync(join(results, 'summary.md'), out.join('\n'));
